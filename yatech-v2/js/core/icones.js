/* Les icônes remplies plutôt que tracées : le trait ne leur va pas. */
const PLEINES = new Set(['points', 'poignee', 'etoile']);

/**
 * Fabrique une icône.
 * @param {string} nom    clé du dessin
 * @param {object} [opts] { taille, epaisseur, classe, titre }
 */
export function icone(nom, opts) {
  const o = opts || {};
  const d = D[nom];
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  if (o.taille) { svg.setAttribute('width', o.taille); svg.setAttribute('height', o.taille); }
  if (o.classe) svg.setAttribute('class', o.classe);
  if (o.titre) {
    svg.removeAttribute('aria-hidden');
    svg.setAttribute('role', 'img');
    const t = document.createElementNS('http://www.w3.org/2000/svg', 'title');
    t.textContent = o.titre;
    svg.appendChild(t);
  }
  if (!d) return svg;            // nom inconnu : un vide, jamais une erreur

  const p = document.createElementNS('http://www.w3.org/2000/svg', 'path');
  p.setAttribute('d', d);
  if (PLEINES.has(nom)) {
    p.setAttribute('fill', 'currentColor');
  } else {
    p.setAttribute('stroke', 'currentColor');
    p.setAttribute('stroke-width', o.epaisseur || 1.7);
    p.setAttribute('stroke-linecap', 'round');
    p.setAttribute('stroke-linejoin', 'round');
  }
  svg.appendChild(p);
  return svg;
}

